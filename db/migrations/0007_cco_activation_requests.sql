CREATE TABLE IF NOT EXISTS "cco_activation_requests" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "consultant_user_id" uuid NOT NULL,
  "slot_position" integer NOT NULL,
  "requested_numeric_part" integer NOT NULL,
  "parent_account_id" uuid NOT NULL,
  "side" "account_side" NOT NULL,
  "amount" numeric(12,2) NOT NULL,
  "transaction_reference" text NOT NULL,
  "senior_consultant_name" text,
  "proof_object_key" text,
  "proof_mime_type" text,
  "status" text DEFAULT 'PENDING' NOT NULL,
  "review_note" text,
  "reviewed_by" uuid,
  "reviewed_at" timestamp with time zone,
  "activated_account_id" uuid,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT "cco_activation_requests_consultant_user_id_users_id_fk" FOREIGN KEY ("consultant_user_id") REFERENCES "public"."users"("id"),
  CONSTRAINT "cco_activation_requests_parent_account_id_network_accounts_id_fk" FOREIGN KEY ("parent_account_id") REFERENCES "public"."network_accounts"("id"),
  CONSTRAINT "cco_activation_requests_reviewed_by_users_id_fk" FOREIGN KEY ("reviewed_by") REFERENCES "public"."users"("id"),
  CONSTRAINT "cco_activation_requests_activated_account_id_network_accounts_id_fk" FOREIGN KEY ("activated_account_id") REFERENCES "public"."network_accounts"("id")
);
